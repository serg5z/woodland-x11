#!/usr/bin/env python3
"""Generates core/x11_colors.c from an X11 rgb.txt (the X colour database).

Lookup keys are normalised the way X servers compare colour names: case-insensitive,
spaces ignored. "grey" spellings are not stored: the lookup maps them to "gray", after
this script checks that every "grey" name in the database equals its "gray" twin.

    tools/gen_colors.py /opt/local/share/X11/rgb.txt > core/x11_colors.c
"""
import sys


def main(path):
    colors = {}
    for line in open(path):
        if line.startswith("!") or not line.strip():
            continue
        r, g, b, name = line.split(None, 3)
        key = name.strip().replace(" ", "").lower()
        val = (int(r), int(g), int(b))
        if key in colors and colors[key] != val:
            sys.exit("conflicting entries for %s" % key)
        colors[key] = val
    for key, val in colors.items():
        if "grey" in key and colors.get(key.replace("grey", "gray")) != val:
            sys.exit("%s has no equal gray twin" % key)
    keep = sorted(k for k in colors if "grey" not in k)
    out = sys.stdout
    out.write("/* X11 colour names (generated by tools/gen_colors.py from rgb.txt; do not edit).\n"
              " * Sorted, lowercase, without spaces; \"grey\" spellings are mapped to \"gray\" in\n"
              " * x11_color_lookup(). %d names. */\n" % len(keep))
    out.write('#include "x11_colors.h"\n\n#include <string.h>\n\n')
    out.write("static const char *const NAMES[%d] = {\n" % len(keep))
    line = "   "
    for k in keep:
        if len(line) + len(k) + 4 > 100:
            out.write(line + "\n")
            line = "   "
        line += ' "%s",' % k
    out.write(line + "\n};\n\n")
    out.write("static const uint8_t RGB[%d][3] = {\n" % len(keep))
    for i in range(0, len(keep), 6):
        out.write("    " + " ".join("{%d, %d, %d}," % colors[keep[j]] for j in range(i, min(i + 6, len(keep)))) + "\n")
    out.write("};\n\n")
    out.write('''int x11_color_lookup(const char *name, size_t n, uint8_t rgb[3]) {
  char k[48];
  size_t m = 0;
  for (size_t i = 0; i < n; ++i) {
    char c = name[i];
    if (c == ' ') continue;
    if (m >= sizeof(k) - 1) return 0;
    k[m++] = (char)(c >= 'A' && c <= 'Z' ? c + 32 : c);
  }
  k[m] = 0;
  for (char *p = strstr(k, "grey"); p; p = strstr(p, "grey")) p[2] = 'a';  /* grey == gray */
  int lo = 0, hi = (int)(sizeof(NAMES) / sizeof(NAMES[0])) - 1;
  while (lo <= hi) {
    int mid = (lo + hi) / 2, c = strcmp(k, NAMES[mid]);
    if (!c) {
      memcpy(rgb, RGB[mid], 3);
      return 1;
    }
    if (c < 0) hi = mid - 1;
    else lo = mid + 1;
  }
  return 0;
}
''')


if __name__ == "__main__":
    main(sys.argv[1])
