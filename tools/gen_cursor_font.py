#!/usr/bin/env python3
"""Generates core/x11_font_cursor.c from the standard X cursor font (cursor.pcf.gz, X.Org
font-cursor-misc; its COPYRIGHT property: 'These "glyphs" are unencumbered').

    tools/gen_cursor_font.py /opt/local/share/fonts/misc/cursor.pcf.gz > core/x11_font_cursor.c
"""
import sys

sys.path.insert(0, __file__.rsplit("/", 1)[0])
import pcf  # noqa: E402

f = pcf.load(sys.argv[1])
assert f["first"] == 0 and len(f["glyphs"]) == f["last"] + 1, "expected glyphs 0..last, all present"
glyphs = [f["glyphs"][c] for c in range(f["last"] + 1)]
for g in glyphs:
    assert g["rsb"] - g["lsb"] <= 16
out = sys.stdout
out.write("/* Generated by tools/gen_cursor_font.py from the X.Org cursor font (cursor.pcf.gz,\n"
          " * font-cursor-misc) -- do not edit. Its COPYRIGHT property: 'These \"glyphs\" are\n"
          " * unencumbered'. %d glyphs; rows: bit x = pixel x right of the glyph's lsb. */\n" % len(glyphs))
out.write('#include "x11_font.h"\n\n')
out.write("const x11_glyph_metrics x11_font_cursor_metrics[%d] = {\n" % len(glyphs))
for i in range(0, len(glyphs), 4):
    out.write("    " + " ".join("{%d, %d, %d, %d, %d}," % (g["lsb"], g["rsb"], g["width"], g["ascent"], g["descent"])
                                 for g in glyphs[i:i + 4]) + "\n")
out.write("};\n\n")
index, rows = [], []
for g in glyphs:
    index.append(len(rows))
    rows.extend(g["rows"])
out.write("const uint16_t x11_font_cursor_index[%d] = {\n" % len(glyphs))
for i in range(0, len(index), 12):
    out.write("    " + " ".join("%d," % v for v in index[i:i + 12]) + "\n")
out.write("};\n\n")
out.write("const uint16_t x11_font_cursor_rows[%d] = {\n" % len(rows))
for i in range(0, len(rows), 10):
    out.write("    " + " ".join("0x%04x," % v for v in rows[i:i + 10]) + "\n")
out.write("};\n")
out.write("const x11_font x11_font_cursor = {\n"
          '    "cursor", 0, 0, %d, %d, %d, %d, %d,\n' % (f["first"], f["last"], f["default_char"], f["ascent"], f["descent"]))
mins = [min(g[k] for g in glyphs) for k in ("lsb", "rsb", "width", "ascent", "descent")]
maxs = [max(g[k] for g in glyphs) for k in ("lsb", "rsb", "width", "ascent", "descent")]
out.write("    {%d, %d, %d, %d, %d}, {%d, %d, %d, %d, %d},\n" % tuple(mins + maxs))
out.write('    x11_font_cursor_metrics, x11_font_cursor_index, x11_font_cursor_rows, 0, "%s", 0, 0, 0, 0, 0, 0, 0};\n' % f["properties"]["FONT"])
